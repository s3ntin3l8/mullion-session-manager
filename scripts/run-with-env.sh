#!/bin/sh
# The launchd launcher — the macOS analogue of the systemd unit's
# EnvironmentFile= + ExecStart= pair (issue #1718, roadmap 8.4).
#
# launchd has no EnvironmentFile, and the systemd unit's EnvironmentFile= is
# exactly what makes the install's .env visible at every start. Inlining the
# .env's values into the plist would freeze them at install time — an
# operator could no longer edit MULLION_ROLE, the auth vars or the frontend
# settings without re-installing. So the plist runs this script instead: it
# sources the .env and execs node, which is what systemd would have done.
#
# The paths come from the plist's EnvironmentVariables (MULLION_HOME and
# MULLION_NODE_BIN), so nothing here depends on PATH — a launchd agent gets
# a minimal PATH (the same reason the systemd unit inlines an absolute
# ExecStart: see deploy/mullion.service's comment on nvm).
#
# `set -a` makes the sourced variables exported, so they land in node's
# environment; `exec` replaces this shell with node, so launchd's job is
# node's process (and launchd tracks it as such). The relative
# `dist/server.js` resolves against the job's WorkingDirectory — the
# versioned-release layout's `current` symlink — exactly as the systemd
# unit's relative ExecStart resolves against its own WorkingDirectory.

set -a
# shellcheck disable=SC1091  # the .env is generated by the installer; its path is dynamic.
. "$MULLION_HOME/.env"
set +a

exec "$MULLION_NODE_BIN" dist/server.js
